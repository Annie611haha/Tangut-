class DualEncoderInheritanceModel(nn.Module):
    """
    """
    def __init__(self, bert_model_path, comp_vocab_size,
                 comp_dim=768, hidden_dim=768):
        super().__init__()

        self.bert = BertModel.from_pretrained(bert_model_path)
        for param in self.bert.pooler.parameters():
            param.requires_grad = False

        self.comp_embedding = nn.Embedding(comp_vocab_size, comp_dim, padding_idx=0)
        self.comp_proj = nn.Linear(comp_dim, hidden_dim)

        self.attn_query = nn.Parameter(torch.randn(hidden_dim))
        self.attn_key = nn.Linear(hidden_dim, hidden_dim)

        self.fusion_gate = nn.Linear(hidden_dim * 2, 1)

        self.compare_layer = nn.Sequential(
            nn.Linear(hidden_dim * 2, hidden_dim),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(),
            nn.Dropout(0.3),
        )

        self.phonetic_head = nn.Linear(hidden_dim // 2, 1)
        self.semantic_head = nn.Linear(hidden_dim // 2, 1)

    def encode_single_char(self, bert_input_ids, attention_mask,
                           comp_ids, comp_mask):
        outputs = self.bert(bert_input_ids, attention_mask=attention_mask)
        h_bert = outputs.last_hidden_state[:, 0, :]  # [CLS]

        comp_emb = self.comp_embedding(comp_ids)
        comp_emb = self.comp_proj(comp_emb)

        comp_mask_3d = comp_mask.unsqueeze(-1)
        attn_keys = self.attn_key(comp_emb)
        attn_scores = torch.matmul(attn_keys, self.attn_query) / (comp_emb.size(-1) ** 0.5)
        attn_scores = attn_scores.masked_fill(comp_mask_3d.squeeze(-1) == 0, -1e9)
        attn_weights = F.softmax(attn_scores, dim=1).unsqueeze(-1)
        h_comp = (comp_emb * attn_weights).sum(dim=1)

        alpha = torch.sigmoid(self.fusion_gate(torch.cat([h_bert, h_comp], dim=-1)))
        h_fused = alpha * h_bert + (1 - alpha) * h_comp

        return h_fused, alpha

    def forward(self, batch):
        h_base, alpha_base = self.encode_single_char(
            batch['base_bert_input_ids'], batch['base_bert_attention_mask'],
            batch['base_comp_ids'], batch['base_comp_mask']
        )
        h_derived, alpha_derived = self.encode_single_char(
            batch['derived_bert_input_ids'], batch['derived_bert_attention_mask'],
            batch['derived_comp_ids'], batch['derived_comp_mask']
        )

        h_combined = torch.cat([h_base, h_derived], dim=-1)
        h_compare = self.compare_layer(h_combined)

        phonetic_logits = self.phonetic_head(h_compare).squeeze(-1)
        semantic_logits = self.semantic_head(h_compare).squeeze(-1)

        return {
            'phonetic_logits': phonetic_logits,
            'semantic_logits': semantic_logits,
            'h_base': h_base,
            'h_derived': h_derived,
            'alpha_base': alpha_base,
            'alpha_derived': alpha_derived,
        }

