def find_compound_basic_in_char(comps, compound_basic_seqs):
    matches = []
    n = len(comps)
    for length in range(2, n + 1):
        for indices in combinations(range(n), length):
            subseq = tuple(comps[i] for i in indices)
            if subseq in compound_basic_seqs:
                matches.append(indices)
    return matches


