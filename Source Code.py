class BaseDerivedDataset(Dataset):

    def __init__(self, data, max_components=MAX_COMPONENTS):
        self._data = data
        self._max_components = max_components

    def __len__(self):
        return len(self._data)

    def __getitem__(self, idx):
        p = self._data[idx]

        base_comp_ids = list(p['base_comp_ids'])
        base_comp_len = len(base_comp_ids)
        base_pad_len = self._max_components - base_comp_len

        derived_comp_ids = list(p['derived_comp_ids'])
        derived_comp_len = len(derived_comp_ids)
        derived_pad_len = self._max_components - derived_comp_len

        return {
            'base_bert_input_ids': p['base_bert_input_ids'].clone(),
            'base_bert_attention_mask': p['base_bert_attention_mask'].clone(),
            'base_comp_ids': torch.tensor(base_comp_ids + [0] * base_pad_len, dtype=torch.long),
            'base_comp_mask': torch.tensor([1] * base_comp_len + [0] * base_pad_len, dtype=torch.float),

            'derived_bert_input_ids': p['derived_bert_input_ids'].clone(),
            'derived_bert_attention_mask': p['derived_bert_attention_mask'].clone(),
            'derived_comp_ids': torch.tensor(derived_comp_ids + [0] * derived_pad_len, dtype=torch.long),
            'derived_comp_mask': torch.tensor([1] * derived_comp_len + [0] * derived_pad_len, dtype=torch.float),

            'phonetic_label': torch.tensor(p['phonetic_label'], dtype=torch.float),
            'semantic_label': torch.tensor(p['semantic_label'], dtype=torch.float),
        }

